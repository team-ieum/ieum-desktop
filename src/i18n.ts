export const dict = { ko, en };
export type Lang = keyof typeof dict;

let lang: Lang = "ko";

export const setLang = (l: Lang) => {
  lang = l;
};
export const getLang = () => lang;
/** 날짜·숫자 표시용 로케일. */
export const locale = () => (lang === "ko" ? "ko-KR" : "en-US");

/** 설정값 → 화면 언어. `system`이면 시스템 언어가 ko로 시작할 때만 ko. */
export const resolveLang = (setting: Settings["language"], system: string): Lang =>
  setting === "system" ? (system.toLowerCase().startsWith("ko") ? "ko" : "en") : setting;

export const t = (key: Key): string => dict[lang][key];

/** 노드 정의에서 만든 키처럼 동적인 키 — 없으면 undefined. */
export const tDyn = (key: string): string | undefined => (dict[lang] as Record<string, string>)[key];
